  const LANGS = ['zh', 'ja', 'en'];
  const FALLBACK = 'zh';

  
  function detect(navLang) {
    const l = String(navLang || '').toLowerCase();
    if (l.startsWith('ja')) return 'ja';
    if (l.startsWith('zh')) return 'zh';
    if (l.startsWith('en')) return 'en';
    return FALLBACK;
  }

  
  function resolve(lang, navLang) {
    if (!lang || lang === 'auto') return detect(navLang);
    return LANGS.includes(lang) ? lang : FALLBACK;
  }

  
  function translate(lang, key, vars) {
    const table = DICT[lang] || DICT[FALLBACK];
    let text = table[key];
    if (text === undefined) text = DICT[FALLBACK][key];
    if (text === undefined) return key;
    if (vars) {
      text = text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] === undefined ? m : String(vars[name])));
    }
    return text;
  }

  return { DICT, LANGS, FALLBACK, detect, resolve, translate };
